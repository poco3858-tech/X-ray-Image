class CustomDataGenerator(Sequence):
    def __init__(self, df, batch_size, is_training, datagen):
        super().__init__()
        self.df = df.reset_index(drop=True)
        self.batch_size = batch_size
        self.is_training = is_training
        self.datagen = datagen
        self.indices = np.arange(len(self.df))
        self.on_epoch_end()

    def __len__(self):
        return int(np.ceil(len(self.df) / self.batch_size))

    def __getitem__(self, idx):
        idxs = self.indices[idx*self.batch_size : (idx+1)*self.batch_size]
        part = self.df.iloc[idxs]

        imgs = []
        for fn in part['filename']:
            im = tf.keras.preprocessing.image.load_img(fn, target_size=(224, 224))
            im = tf.keras.preprocessing.image.img_to_array(im)
            imgs.append(im)
        imgs = np.array(imgs)
        it = self.datagen.flow(imgs, batch_size=len(imgs), shuffle=False)
        imgs = next(it)

        dens = part['density_normalized'].values.reshape(-1, 1).astype('float32')

        y = label_encoder.transform(part['label'])
        y = tf.keras.utils.to_categorical(y, num_classes=num_classes)

        return {'image_input': imgs, 'density_input': dens}, y

    def on_epoch_end(self):
        if self.is_training:
            np.random.shuffle(self.indices)

