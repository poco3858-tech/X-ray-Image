def build_fixed_model():
    image_input   = Input(shape=(224, 224, 3), name='image_input')
    density_input = Input(shape=(1,),          name='density_input')

    base = VGG16(input_tensor=image_input, include_top=False, weights='imagenet')
    base.trainable = True
    for l in base.layers[:10]:
        l.trainable = False

    x = base.output
    x = GlobalAveragePooling2D()(x)
    x = BatchNormalization()(x)
    x = Concatenate()([x, density_input])

    # --- Fixed hyperparameters (as requested) ---
    x = Dense(256, activation='relu')(x)          # units_dense1
    x = Dropout(0.3)(x)                           # dropout_rate1
    x = Dense(384, activation='relu')(x)          # units_dense2
    x = Dropout(0.3)(x)                           # dropout_rate2
    outputs = Dense(num_classes, activation='softmax')(x)

    model = Model(inputs=[image_input, density_input], outputs=outputs)
    model.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=3.940584533583884e-05),
        loss='categorical_crossentropy',
        metrics=['accuracy']
    )
    return model

