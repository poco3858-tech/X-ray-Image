def build_model(hp):
    image_input   = Input(shape=(224, 224, 3), name='image_input')
    density_input = Input(shape=(1,),          name='density_input')

    base_model = VGG16(input_tensor=image_input, include_top=False, weights='imagenet')
    base_model.trainable = True
    for layer in base_model.layers[:10]:
        layer.trainable = False

    x = base_model.output
    x = GlobalAveragePooling2D()(x)
    x = BatchNormalization()(x)
    x = Concatenate()([x, density_input])

    x = Dense(hp.Int('units_dense1', 256, 1024, step=256), activation='relu')(x)
    x = Dropout(hp.Float('dropout_rate1', 0.3, 0.7, step=0.1))(x)
    x = Dense(hp.Int('units_dense2', 128, 512, step=128), activation='relu')(x)
    x = Dropout(hp.Float('dropout_rate2', 0.3, 0.7, step=0.1))(x)
    outputs = Dense(num_classes, activation='softmax')(x)

    model = Model(inputs=[image_input, density_input], outputs=outputs)
    model.compile(
        optimizer=tf.keras.optimizers.Adam(
            learning_rate=hp.Float('learning_rate', 1e-5, 1e-3, sampling='log')
        ),
        loss='categorical_crossentropy',
        metrics=['accuracy']
    )
    return model

